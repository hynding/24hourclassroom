// Writes www/page-head.config.php after `stencil build`: the API base URL
// for index.php (src/server/), which asks the API for each public page's
// <head>. Same build-time API_BASE_URL as the bundle and robots.txt.
const fs = require('fs');
const path = require('path');

/** A PHP single-quoted literal: only \ and ' need escaping. */
const phpString = (value) => `'${String(value).replace(/[\\']/g, (c) => `\\${c}`)}'`;

function pageHeadConfig(apiBaseUrl) {
  const base = String(apiBaseUrl).replace(/\/+$/, '');
  return `<?php\n// Generated by scripts/page-head-config.js at build time.\nreturn ['api' => ${phpString(base)}];\n`;
}

module.exports = { pageHeadConfig };

if (require.main === module) {
  const out = path.join(__dirname, '..', 'www', 'page-head.config.php');
  fs.writeFileSync(out, pageHeadConfig(process.env.API_BASE_URL ?? 'http://localhost:8000'));
}
